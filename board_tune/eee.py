"""Deferred per-device EEE policies, including older NetworkManager releases."""

import re

from board_tune import systemd
from board_tune.errors import Error

MARKER = '# Generated by board-tune: EEE policy\n'


def _escape(text):
    # systemd-escape's unit-name escaping (hyphens must be escaped too).
    return ''.join(c if c.isascii() and (c.isalnum() or c in ':_.')
                   and not (i == 0 and c == '.') else f'\\x{ord(c):02x}'
                   for i, c in enumerate(text))


def paths(iface):
    name = f'board-tune-eee-{_escape(iface)}.service'
    return name, f'{systemd.SYSTEM_DIR}/{name}', f'/etc/NetworkManager/dispatcher.d/90-board-tune-eee-{iface}'


def binary(plan):
    return next((p for p in ('/usr/sbin/ethtool', '/usr/bin/ethtool', '/sbin/ethtool', '/bin/ethtool')
                 if plan.exists(p)), None)


def policy(plan, iface):
    _, path, _ = paths(iface)
    text = plan.read_text(path) or ''
    if text.startswith(MARKER):
        match = re.search(r'^ExecStart=\S+ --set-eee \S+ eee (on|off)$', text, re.M)
        if match and systemd.is_enabled(plan, paths(iface)[0]):
            return 'ENABLE' if match[1] == 'on' else 'DISABLE'
    return 'KEEP'


def plan_policy(ctx, iface):
    cfg, plan = ctx.config, ctx.plan
    mode = next((m for m in ('DISABLE', 'ENABLE', 'REMOVE') if cfg.enabled(f'NETWORK_EEE_{m}')), None)
    if mode is None:
        return
    unit, path, dispatcher = paths(iface)
    for owned in (path, dispatcher):
        old = plan.read_text(owned)
        # Refuse to overwrite administrator files under a managed filename.
        if plan.exists(owned) and (plan.readlink(owned) is not None or not old or
                                  not old.startswith(MARKER if owned == path else '#!/bin/sh\n' + MARKER)):
            raise Error(f'EEE policy: {owned} is not owned by board-tune')
    if mode == 'REMOVE':
        links = systemd.disable(plan, unit)
        plan.remove(path)
        plan.remove(dispatcher)
        systemd.daemon_reload(plan, [path, *links])
        if plan.changed(path, dispatcher, *links):
            plan.note(f'EEE policy for {iface} removed; driver defaults return on reboot/device reattachment')
        return
    if policy(plan, iface) == mode:
        # Readback also selects ENABLE/DISABLE. An unchanged stored policy
        # must not probe hardware or block unrelated Ethernet edits.
        return
    ethtool = binary(plan)
    if ethtool is None:
        raise Error('EEE configuration requires ethtool installed on the target')
    if ctx.target.live:
        if not ctx.target.exists(f'/sys/class/net/{iface}'):
            raise Error(f'EEE: interface {iface} does not exist on the running target')
        unsupported = False
        try:
            out = ctx.target.run(['env', 'LC_ALL=C', 'timeout', '8', ethtool, '--show-eee', iface])
        except Error as error:
            if 'operation not supported' not in str(error).lower():
                raise Error(f'EEE support on {iface} could not be verified; no policy applied: {error}') from None
            unsupported, out = True, ''
        if unsupported or re.search(r'EEE status:\s*not supported\b', out, re.I):
            plan.note(f'EEE is not supported by the driver on {iface}; requested policy skipped, '
                      'existing EEE settings kept. Other changes can still be applied.')
            return
        if not re.search(r'EEE status:\s*(enabled|disabled)\b', out):
            raise Error(f'EEE is not supported or its status is unavailable on {iface}; no policy applied')
    else:
        plan.note(f'EEE hardware support on {iface} cannot be verified on an offline target')
    device = f'sys-subsystem-net-devices-{_escape(iface)}.device'
    state = 'off' if mode == 'DISABLE' else 'on'
    plan.write(path, MARKER + '[Unit]\n'
               f'Description=Set EEE {state} on {iface}\nBindsTo={device}\nAfter={device}\n'
               '[Service]\nType=oneshot\nRemainAfterExit=yes\nTimeoutStartSec=10\n'
               f'ExecStart={ethtool} --set-eee {iface} eee {state}\n'
               f'[Install]\nWantedBy={device}\n', mode=0o644, owner=(0, 0))
    links = systemd.enable(plan, unit)
    # NM may reset driver settings on activation. Apply after each successful
    # activation too; no dispatcher event or service start is triggered by apply.
    if plan.exists('/etc/NetworkManager'):
        plan.write(dispatcher, '#!/bin/sh\n' + MARKER +
                   f'[ "$1" = "{iface}" ] && [ "$2" = up ] || exit 0\n'
                   f'exec {ethtool} --set-eee {iface} eee {state}\n', mode=0o755, owner=(0, 0))
    systemd.daemon_reload(plan, [path, *links])
    if plan.changed(path, dispatcher, *links):
        plan.note(f'EEE {state} policy for {iface} applies on next boot/device attachment or NetworkManager reconnect; live link unchanged')
