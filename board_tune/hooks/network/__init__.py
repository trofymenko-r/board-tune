"""Wired network: one Ethernet interface with DHCP or a static address."""

from __future__ import annotations

import ipaddress
import re
import uuid
from dataclasses import dataclass

from board_tune import systemd
from board_tune.errors import Error, Unsupported
from board_tune.registry import Context, Hook

NM_DIR = "/etc/NetworkManager"
NETWORKD_DIR = "/etc/systemd/network"
# Connection UUIDs derive from the name, so re-runs produce the same file.
UUID_NAMESPACE = uuid.UUID("559c1b0e-5dc9-44d7-a695-b17d12016895")
_IFACE = re.compile(r"[A-Za-z0-9_.:-]{1,15}")


@dataclass
class Settings:
    iface: str
    address: ipaddress.IPv4Interface | None = None
    gateway: ipaddress.IPv4Address | None = None
    dns: tuple[ipaddress.IPv4Address, ...] = ()


def _ip(symbol: str, text: str):
    try:
        return ipaddress.IPv4Address(text)
    except ValueError:
        raise Error(f"{symbol}: '{text}' is not an IPv4 address") from None


def settings(cfg) -> Settings:
    iface = cfg.str("NETWORK_IFACE")
    if not _IFACE.fullmatch(iface):
        raise Error(f"NETWORK_IFACE: '{iface}' is not a valid interface name")
    s = Settings(iface)
    if not cfg.enabled("NETWORK_STATIC"):
        return s
    address = cfg.str("NETWORK_ADDRESS")
    try:
        if "/" not in address:
            raise ValueError
        s.address = ipaddress.IPv4Interface(address)
    except ValueError:
        raise Error(f"NETWORK_ADDRESS: '{address}' is not an IPv4 address with "
                    "a prefix length, e.g. 192.168.1.50/24") from None
    if cfg.str("NETWORK_GATEWAY"):
        s.gateway = _ip("NETWORK_GATEWAY", cfg.str("NETWORK_GATEWAY"))
    s.dns = tuple(_ip("NETWORK_DNS", d) for d in cfg.str("NETWORK_DNS").split())
    return s


def networkmanager_keyfile(s: Settings) -> tuple[str, str]:
    name = f"board-tune-{s.iface}"
    lines = [
        "# Generated by board-tune",
        "[connection]",
        f"id={name}",
        f"uuid={uuid.uuid5(UUID_NAMESPACE, name)}",
        "type=ethernet",
        f"interface-name={s.iface}",
        # Preferred over the automatic "Wired connection 1".
        "autoconnect-priority=100",
        "",
        "[ethernet]",
        "",
        "[ipv4]",
    ]
    if s.address is None:
        lines.append("method=auto")
    else:
        lines += ["method=manual", f"address1={s.address}"]
        if s.gateway:
            lines.append(f"gateway={s.gateway}")
        if s.dns:
            lines.append("dns=" + "".join(f"{d};" for d in s.dns))
    lines += ["", "[ipv6]", "method=auto"]
    return f"{NM_DIR}/system-connections/{name}.nmconnection", "\n".join(lines) + "\n"


def networkd_file(s: Settings) -> tuple[str, str]:
    lines = ["# Generated by board-tune", "[Match]", f"Name={s.iface}", "", "[Network]"]
    if s.address is None:
        lines.append("DHCP=ipv4")
    else:
        lines.append(f"Address={s.address}")
        if s.gateway:
            lines.append(f"Gateway={s.gateway}")
        lines += [f"DNS={d}" for d in s.dns]
    return f"{NETWORKD_DIR}/10-board-tune-{s.iface}.network", "\n".join(lines) + "\n"


def _sections(text: str) -> dict[str, dict[str, list[str]]]:
    """Read simple keyfiles, keeping repeated networkd Address/DNS entries."""
    out = {}
    section = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", ";")):
            continue
        if line.startswith("[") and line.endswith("]"):
            section = out.setdefault(line[1:-1], {})
        elif section is not None and "=" in line:
            key, value = line.split("=", 1)
            section.setdefault(key.strip(), []).append(value.strip())
    return out


def _first(section, key, default=""):
    return section.get(key, [default])[0]


def _network_values(iface, method, address="", gateway="", dns=""):
    if not _IFACE.fullmatch(iface) or method not in ("auto", "manual"):
        return None
    values = {"NETWORK": "y", "NETWORK_IFACE": iface,
              "NETWORK_STATIC" if method == "manual" else "NETWORK_DHCP": "y"}
    if method == "manual":
        address, _, legacy_gateway = address.partition(",")
        try:
            if "/" not in address:
                return None
            address = str(ipaddress.IPv4Interface(address))
            gateway = gateway or legacy_gateway
            if gateway:
                gateway = str(ipaddress.IPv4Address(gateway))
            servers = [str(ipaddress.IPv4Address(d)) for d in dns.replace(";", " ").split()]
        except ValueError:
            return None
        values.update(NETWORK_ADDRESS=address, NETWORK_GATEWAY=gateway,
                      NETWORK_DNS=" ".join(servers))
    return values


class WiredNetwork(Hook):
    title = "Ethernet"
    symbol = "NETWORK"
    order = 30

    def read(self, ctx: Context) -> dict[str, str]:
        candidates = []
        preferred = ctx.config.str("NETWORK_IFACE") or "eth0"
        if ctx.plan.exists(NM_DIR):
            for directory in (f"{NM_DIR}/system-connections", "/run/NetworkManager/system-connections"):
                for name in ctx.target.listdir(directory):
                    if not name.endswith(".nmconnection"):
                        continue
                    sections = _sections(ctx.plan.read_text(f"{directory}/{name}") or "")
                    connection = sections.get("connection", {})
                    if _first(connection, "type") not in ("ethernet", "802-3-ethernet"):
                        continue
                    if _first(connection, "autoconnect").lower() in ("false", "no", "0"):
                        continue
                    ipv4 = sections.get("ipv4", {})
                    iface = _first(connection, "interface-name", preferred)
                    if "interface-name" not in connection:
                        ctx.plan.note(f"Ethernet profile {name} has no interface binding; showing {iface}")
                    values = _network_values(iface, _first(ipv4, "method"),
                                             _first(ipv4, "address1"), _first(ipv4, "gateway"),
                                             _first(ipv4, "dns"))
                    if values is None:
                        ctx.plan.note(f"network profile {name} cannot be represented in the menu")
                        continue
                    values["NETWORK_BACKEND_NM"] = "y"
                    try:
                        priority = int(_first(connection, "autoconnect-priority", "0"))
                    except ValueError:
                        priority = 0
                    candidates.append(((iface != preferred, -priority, name), values))
        else:
            files = {}
            for directory in ("/usr/lib/systemd/network", "/run/systemd/network", NETWORKD_DIR):
                for name in ctx.target.listdir(directory):
                    if name.endswith(".network"):
                        files[name] = f"{directory}/{name}"
            for name, path in sorted(files.items()):
                if ctx.plan.readlink(path) == "/dev/null":
                    continue
                sections = _sections(ctx.plan.read_text(path) or "")
                match = sections.get("Match", {})
                network = sections.get("Network", {})
                iface = _first(match, "Name")
                addresses = network.get("Address", [])
                dhcp = _first(network, "DHCP").lower() in ("yes", "true", "ipv4", "1")
                values = _network_values(iface, "auto" if dhcp else "manual",
                                         addresses[0] if addresses else "",
                                         _first(network, "Gateway"), " ".join(network.get("DNS", [])))
                if values is None:
                    ctx.plan.note(f"network profile {name} cannot be represented in the menu")
                    continue
                values["NETWORK_BACKEND_NETWORKD"] = "y"
                candidates.append(((iface != preferred, 0, name), values))
        if not candidates:
            return {"NETWORK": "n"}
        if len(candidates) > 1:
            ctx.plan.note("multiple Ethernet profiles found; the menu shows one interface/profile")
        return min(candidates, key=lambda item: item[0])[1]

    def plan(self, ctx: Context) -> None:
        s = settings(ctx.config)
        if self._backend(ctx) == "nm":
            path, text = networkmanager_keyfile(s)
            ctx.plan.write(path, text, mode=0o600, owner=(0, 0))
            if ctx.plan.changed(path):
                # Makes NetworkManager see the profile without activating it.
                ctx.plan.command(["nmcli", "connection", "reload"])
        else:
            path, text = networkd_file(s)
            ctx.plan.write(path, text, mode=0o644, owner=(0, 0))
            systemd.daemon_reload(
                ctx.plan, systemd.enable(ctx.plan, "systemd-networkd.service"))
        if ctx.plan.changed(path):
            ctx.plan.note(f"network settings for {s.iface} take effect after a reboot")

    @staticmethod
    def _backend(ctx: Context) -> str:
        cfg = ctx.config
        has_nm = ctx.plan.exists(NM_DIR)
        if cfg.enabled("NETWORK_BACKEND_NM"):
            if not has_nm:
                raise Error("NETWORK_BACKEND_NM: NetworkManager is not installed on the target")
            return "nm"
        if cfg.enabled("NETWORK_BACKEND_NETWORKD"):
            return "networkd"
        if has_nm:
            return "nm"
        if systemd.find_unit(ctx.plan, "systemd-networkd.service"):
            return "networkd"
        raise Unsupported(f"{ctx.target.description}: neither NetworkManager nor "
                          "systemd-networkd found")


HOOK = WiredNetwork()
