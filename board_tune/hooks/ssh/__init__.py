"""SSH server: start at boot, sshd settings and authorized keys."""

from __future__ import annotations

import os
import re

from board_tune import accounts, systemd
from board_tune.errors import Error
from board_tune.registry import Context, Hook

SSHD_CONFIG = "/etc/ssh/sshd_config"
# sshd uses the first value it reads, so sort early among the drop-ins.
DROPIN = "/etc/ssh/sshd_config.d/10-board-tune.conf"
NOT_TO_BE_RUN = "/etc/ssh/sshd_not_to_be_run"
UNITS = ("ssh.service", "sshd.service")

ROOT_LOGIN = {
    "SSH_ROOT_LOGIN_NO": "no",
    "SSH_ROOT_LOGIN_KEY": "prohibit-password",
    "SSH_ROOT_LOGIN_YES": "yes",
}
PASSWORD_AUTH = {
    "SSH_PASSWORD_AUTH_NO": "no",
    "SSH_PASSWORD_AUTH_YES": "yes",
}


def _choice(cfg, values: dict[str, str]) -> str | None:
    return next((v for sym, v in values.items() if cfg.enabled(sym)), None)


class SSHServer(Hook):
    title = "SSH server"
    symbol = "SSH"
    order = 40

    def plan(self, ctx: Context) -> None:
        unit = next((u for u in UNITS if systemd.find_unit(ctx.plan, u)), None)
        if unit is None:
            raise Error(f"{ctx.target.description}: the OpenSSH server is not installed")
        if ctx.config.enabled("SSH_ENABLE"):
            links = systemd.enable(ctx.plan, unit)
            ctx.plan.remove(NOT_TO_BE_RUN)
            systemd.daemon_reload(ctx.plan, links)
        self._sshd_config(ctx, unit)
        keys = ctx.config.str("SSH_AUTHORIZED_KEYS")
        if keys:
            self._authorized_keys(ctx, keys)

    def _sshd_config(self, ctx: Context, unit: str) -> None:
        cfg = ctx.config
        lines = []
        if cfg.int("SSH_PORT") != 22:
            lines.append(f"Port {cfg.int('SSH_PORT')}")
        root_login = _choice(cfg, ROOT_LOGIN)
        if root_login:
            lines.append(f"PermitRootLogin {root_login}")
        password = _choice(cfg, PASSWORD_AUTH)
        if password:
            lines.append(f"PasswordAuthentication {password}")

        if not lines:
            ctx.plan.remove(DROPIN)
        else:
            main = ctx.plan.read_text(SSHD_CONFIG) or ""
            if not re.search(r"(?mi)^\s*Include\s+\S*sshd_config\.d/", main):
                raise Error(f"{SSHD_CONFIG} does not include sshd_config.d; "
                            "cannot apply the SSH server settings")
            ctx.plan.write(DROPIN, "# Generated by board-tune\n" + "\n".join(lines) + "\n",
                           mode=0o644, owner=(0, 0))
        if ctx.plan.changed(DROPIN):
            # Validate before reloading: a broken sshd must not lock us out.
            ctx.plan.command(["/usr/sbin/sshd", "-t"])
            ctx.plan.command(["systemctl", "try-reload-or-restart", unit])

    def _authorized_keys(self, ctx: Context, source: str) -> None:
        path = os.path.expanduser(source)
        try:
            with open(path) as f:
                keys = [line.strip() for line in f
                        if line.strip() and not line.lstrip().startswith("#")]
        except OSError as e:
            raise Error(f"SSH_AUTHORIZED_KEYS: cannot read {path}: {e.strerror}") from None
        if not keys:
            raise Error(f"SSH_AUTHORIZED_KEYS: no keys in {path}")

        user = ctx.config.str("SSH_AUTHORIZED_KEYS_USER")
        account = accounts.lookup(ctx.plan, user)
        if account is None:
            raise Error(f"SSH_AUTHORIZED_KEYS_USER: user '{user}' does not exist "
                        "on the target")
        owner = (account.uid, account.gid)
        ssh_dir = account.home.rstrip("/") + "/.ssh"
        authorized = f"{ssh_dir}/authorized_keys"
        ctx.plan.mkdir(ssh_dir, 0o700, owner)

        text = ctx.plan.read_text(authorized) or ""
        present = {line.strip() for line in text.splitlines()}
        missing = [k for k in keys if k not in present]
        if missing:
            if text and not text.endswith("\n"):
                text += "\n"
            text += "\n".join(missing) + "\n"
        ctx.plan.write(authorized, text, mode=0o600, owner=owner)


HOOK = SSHServer()
