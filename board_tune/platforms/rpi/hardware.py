"""Primary header bus settings; intentionally no runtime pin changes."""

import re

from . import configtxt

I2C_MODULES = "/etc/modules-load.d/board-tune-i2c.conf"
PARAMS = {"i2c": "I2C", "i2c_arm": "I2C", "spi": "SPI"}
ON = {"on", "true", "yes", "1"}
OFF = {"off", "false", "no", "0"}


def read(ctx, directory):
    """Import explicit base dtparams, keeping uncertain settings as actions.

    This is boot-file readback, not a claim about the running device tree.
    Includes, runtime filters and overlay-exported parameters are deliberately
    not evaluated. An unknown assignment invalidates an earlier known value.
    """
    states = {}
    model, conditional, overlay = True, False, False
    for raw in (ctx.plan.read_text(f"{directory}/config.txt") or "").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line == "[all]":
            model, conditional = True, False
        elif line == "[none]":
            model = False
        elif re.fullmatch(r"\[pi[0-5]\]", line):
            model = line == f"[{ctx.board.filter}]"
        elif line.startswith("["):
            # GPIO/serial/EDID/CM-specific filters need more than a board family.
            conditional = True
        elif model and re.match(r"include\s", line):
            states = {bus: None for bus in PARAMS.values()}
            conditional, overlay = True, True
            ctx.plan.note("hardware boot settings in config.txt include files are unknown; "
                          "uncertain buses stay at Keep")
        elif model and line.startswith("dtoverlay="):
            overlay = conditional or bool(line.partition("=")[2].strip())
        elif model and line.startswith(("dtparam=", "device_tree_param=")):
            for param in line.partition("=")[2].split(","):
                key, sep, value = param.strip().partition("=")
                bus = PARAMS.get(key)
                if bus is None:
                    continue
                value = value.strip().lower() if sep else "on"
                if conditional or overlay or value not in ON | OFF:
                    states[bus] = None
                    ctx.plan.note("some hardware boot settings have conditional/overlay "
                                  "scope or unknown values; uncertain buses stay at Keep")
                else:
                    states[bus] = value in ON

    # Absent directives are not proof of a disabled bus: overlays/HATs can
    # enable controllers. Never infer runtime status from boot-file absence.
    values = {"HARDWARE": "y"}
    for bus in ("I2C", "SPI"):
        enabled = states.get(bus)
        action = "KEEP" if enabled is None else "ENABLE" if enabled else "DISABLE"
        values[f"HARDWARE_{bus}_{action}"] = "y"
    ctx.plan.note("hardware menu shows explicit base boot parameters, not running "
                  "bus status; device overlays and HAT pin conflicts are not evaluated")
    return values


def setup(ctx, directory):
    cfg, plan = ctx.config, ctx.plan
    path = f"{directory}/config.txt"
    for bus, param in (("I2C", "i2c_arm"), ("SPI", "spi")):
        if cfg.enabled(f"HARDWARE_{bus}_KEEP"):
            continue
        enabled = cfg.enabled(f"HARDWARE_{bus}_ENABLE")
        # Appending ensures later site directives cannot override our choice.
        # Reset conditional filters and overlay parameter scope first.
        lines = ["[all]", f"[{ctx.board.filter}]", "dtoverlay=",
                 f"dtparam={param}={'on' if enabled else 'off'}", "[all]"]
        text = plan.read_text(path)
        updated = configtxt.set_block(text, f"hardware_{bus.lower()}", lines, at_end=True)
        if updated != text:
            plan.write(path, updated)
        if bus == "I2C":
            # i2c-dev is shared by all adapters, including camera buses.
            # Disabling the header controller must preserve their /dev nodes.
            plan.write(I2C_MODULES, "# Generated by board-tune\ni2c-dev\n",
                       mode=0o644, owner=(0, 0))
