import textwrap

import pytest

from board_tune.cli import main

DROPIN = "etc/ssh/sshd_config.d/10-board-tune.conf"
WANTS = "etc/systemd/system/multi-user.target.wants/ssh.service"
KEY = "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIExampleKeyForTestsOnly user@host"


@pytest.fixture
def run(rootfs, tmp_path, capsys):
    def run(config, expect=0):
        path = tmp_path / "profile.cfg"
        path.write_text("CONFIG_BOARD_RPI4=y\nCONFIG_SSH=y\n" + textwrap.dedent(config))
        rc = main([str(rootfs), "--load", str(path), "-y"])
        out, err = capsys.readouterr()
        assert rc == expect, err
        return out + err
    return run


def test_enable_only(rootfs, run):
    (rootfs / "etc/ssh/sshd_not_to_be_run").touch()
    run("")
    assert (rootfs / WANTS).is_symlink()
    assert (rootfs / "etc/systemd/system/sshd.service").is_symlink()
    assert not (rootfs / "etc/ssh/sshd_not_to_be_run").exists()
    assert not (rootfs / DROPIN).exists()
    assert "Nothing to change." in run("")


def test_enable_disabled_leaves_service_alone(rootfs, run):
    run("# CONFIG_SSH_ENABLE is not set\n")
    assert not (rootfs / WANTS).exists()


def test_sshd_settings(rootfs, run):
    run("""\
        CONFIG_SSH_PORT=2222
        CONFIG_SSH_ROOT_LOGIN_KEY=y
        CONFIG_SSH_PASSWORD_AUTH_NO=y
    """)
    assert (rootfs / DROPIN).read_text() == (
        "# Generated by board-tune\nPort 2222\n"
        "PermitRootLogin prohibit-password\nPasswordAuthentication no\n")

    run("")
    assert not (rootfs / DROPIN).exists()


def test_sshd_config_without_include(rootfs, run):
    (rootfs / "etc/ssh/sshd_config").write_text("UsePAM yes\n")
    assert "does not include sshd_config.d" in run("CONFIG_SSH_PORT=2222\n", expect=1)


def test_authorized_keys(rootfs, tmp_path, run):
    pub = tmp_path / "id.pub"
    pub.write_text(KEY + "\n")
    ssh_dir = rootfs / "home/pi/.ssh"
    ssh_dir.mkdir()
    (ssh_dir / "authorized_keys").write_text("ssh-rsa AAAAexisting old@key")
    config = f'CONFIG_SSH_AUTHORIZED_KEYS="{pub}"\nCONFIG_SSH_AUTHORIZED_KEYS_USER="pi"\n'

    run(config)
    assert (ssh_dir / "authorized_keys").read_text() == \
        "ssh-rsa AAAAexisting old@key\n" + KEY + "\n"
    assert ssh_dir.stat().st_mode & 0o777 == 0o700
    assert (ssh_dir / "authorized_keys").stat().st_mode & 0o777 == 0o600
    assert "Nothing to change." in run(config)


def test_authorized_keys_for_root_by_default(rootfs, tmp_path, run):
    pub = tmp_path / "id.pub"
    pub.write_text(KEY + "\n")
    run(f'CONFIG_SSH_AUTHORIZED_KEYS="{pub}"\n')
    assert (rootfs / "root/.ssh/authorized_keys").read_text() == KEY + "\n"


def test_authorized_keys_errors(tmp_path, run):
    assert "cannot read" in run(f'CONFIG_SSH_AUTHORIZED_KEYS="{tmp_path}/nope.pub"\n',
                                expect=1)
    pub = tmp_path / "id.pub"
    pub.write_text(KEY)
    assert "user 'alice' does not exist" in run(
        f'CONFIG_SSH_AUTHORIZED_KEYS="{pub}"\nCONFIG_SSH_AUTHORIZED_KEYS_USER="alice"\n',
        expect=1)


def test_missing_openssh(rootfs, run):
    (rootfs / "usr/lib/systemd/system/ssh.service").unlink()
    assert "OpenSSH server is not installed" in run("", expect=1)
