import shutil
import textwrap

import pytest

from board_tune.cli import main

KEYFILE = "etc/NetworkManager/system-connections/board-tune-eth0.nmconnection"
NETWORKD = "etc/systemd/network/10-board-tune-eth0.network"


@pytest.fixture
def run(rootfs, tmp_path, capsys):
    def run(config, expect=0):
        path = tmp_path / "profile.cfg"
        path.write_text("CONFIG_BOARD_RPI5=y\nCONFIG_NETWORK=y\n" + textwrap.dedent(config))
        rc = main([str(rootfs), "--load", str(path), "-y"])
        out, err = capsys.readouterr()
        assert rc == expect, err
        return out + err
    return run


def test_dhcp_with_networkmanager(rootfs, run):
    out = run("")
    text = (rootfs / KEYFILE).read_text()
    assert "interface-name=eth0\n" in text
    assert "[ipv4]\nmethod=auto\n" in text
    assert (rootfs / KEYFILE).stat().st_mode & 0o777 == 0o600
    assert "take effect after a reboot" in out
    assert "Nothing to change." in run("")


def test_static_with_networkmanager(rootfs, run):
    run("""\
        CONFIG_NETWORK_STATIC=y
        CONFIG_NETWORK_ADDRESS="192.168.1.50/24"
        CONFIG_NETWORK_GATEWAY="192.168.1.1"
        CONFIG_NETWORK_DNS="1.1.1.1 8.8.8.8"
    """)
    text = (rootfs / KEYFILE).read_text()
    assert ("method=manual\naddress1=192.168.1.50/24\ngateway=192.168.1.1\n"
            "dns=1.1.1.1;8.8.8.8;\n") in text


def test_networkd_fallback(rootfs, run):
    shutil.rmtree(rootfs / "etc/NetworkManager")
    run("""\
        CONFIG_NETWORK_IFACE="eth0"
        CONFIG_NETWORK_STATIC=y
        CONFIG_NETWORK_ADDRESS="10.0.0.2/8"
        CONFIG_NETWORK_DNS="10.0.0.1"
    """)
    assert (rootfs / NETWORKD).read_text() == (
        "# Generated by board-tune\n[Match]\nName=eth0\n\n[Network]\n"
        "Address=10.0.0.2/8\nDNS=10.0.0.1\n")
    wants = rootfs / "etc/systemd/system/multi-user.target.wants/systemd-networkd.service"
    assert wants.is_symlink()


def test_explicit_networkmanager_must_exist(rootfs, run):
    shutil.rmtree(rootfs / "etc/NetworkManager")
    assert "NetworkManager is not installed" in run("CONFIG_NETWORK_BACKEND_NM=y\n", expect=1)


@pytest.mark.parametrize("config, message", [
    ('CONFIG_NETWORK_IFACE="eth 0"\n', "not a valid interface name"),
    ('CONFIG_NETWORK_STATIC=y\nCONFIG_NETWORK_ADDRESS="192.168.1.50"\n', "prefix length"),
    ('CONFIG_NETWORK_STATIC=y\nCONFIG_NETWORK_ADDRESS=""\n', "prefix length"),
    ('CONFIG_NETWORK_STATIC=y\nCONFIG_NETWORK_ADDRESS="10.0.0.2/8"\n'
     'CONFIG_NETWORK_GATEWAY="10.0.0"\n', "not an IPv4 address"),
])
def test_validation(run, config, message):
    assert message in run(config, expect=1)
